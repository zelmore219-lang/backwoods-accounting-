"""Exercise the actual UI against a disposable, running local accounting server."""
import argparse
import json
from pathlib import Path
import sys
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
sys.path.insert(0,str(ROOT/'tests'))
from test_accounting import vendor


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--url',default='http://127.0.0.1:8765')
    parser.add_argument('--screenshots',type=Path,default=ROOT/'dist/screenshots')
    args=parser.parse_args()
    args.screenshots.mkdir(parents=True,exist_ok=True)
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
        page=browser.new_page(viewport={'width':1440,'height':1050})
        errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto(args.url)
        page.wait_for_function("document.querySelector('#login-form') || document.querySelector('#content h1')")
        if page.locator('#login-form').count():
            page.screenshot(path=str(args.screenshots/'login.png'),full_page=True)
            form=page.locator('#login-form')
            if form.get_attribute('data-setup')=='yes':
                form.locator('[name=name]').fill('Browser Test Owner')
                form.locator('[name=confirmPassword]').fill('browser-test-passphrase-2026')
            form.locator('[name=username]').fill('browser-owner')
            form.locator('[name=password]').fill('browser-test-passphrase-2026')
            form.get_by_role('button').click()
        page.get_by_role('heading',name='Your business, all together.').wait_for()
        # Direct business expense, independent of the two source apps.
        page.get_by_role('button',name='+ New transaction').click()
        form=page.locator('#manual-document-form')
        form.locator('[name=kind]').select_option('expense')
        form.locator('[name=party]').fill('Electric utility')
        form.locator('[name=reference]').fill('UTILITY-BROWSER')
        form.locator('[name=amount]').fill('45.50')
        form.locator('[name=account]').select_option('5100')
        form.get_by_role('button',name='Save & post').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        # Saved recipe, with waste and burden, never creates journal lines.
        page.locator('nav [data-view=costing]').click()
        page.get_by_role('heading',name='Know what it costs to make.').wait_for()
        form=page.locator('#costing-form')
        form.locator('[name=name]').fill('Root beer · production test')
        component=form.locator('.cost-component').filter(has=page.locator('input')).first
        component.locator('[name=componentName]').fill('Syrup')
        component.locator('[name=componentQuantity]').fill('2')
        component.locator('[name=componentUnit]').fill('lb')
        component.locator('[name=componentCost]').fill('10')
        form.locator('[name=wastePercent]').fill('10')
        form.locator('[name=laborHours]').fill('2')
        form.locator('[name=laborRate]').fill('20')
        form.locator('[name=sellingPrice]').fill('3')
        form.get_by_role('button',name='Calculate production cost').click()
        page.locator('#costing-result').get_by_text('Total batch cost',exact=True).wait_for()
        form.get_by_role('button',name='Save recipe & costs').click()
        page.get_by_text('Production recipe saved. The company ledger was not changed.').wait_for()
        page.screenshot(path=str(args.screenshots/'production-costs.png'),full_page=True)
        page.reload()
        page.locator('nav [data-view=costing]').click()
        page.get_by_role('button',name='Open recipe').first.wait_for()
        # Retail / wholesale channel pricing and durable price plans.
        page.locator('nav [data-view=pricing]').click()
        pricing=page.locator('#pricing-form')
        pricing.locator('[name=name]').fill('Root beer · case of 12')
        pricing.locator('[name=unitCost]').fill('1')
        pricing.locator('[name=caseQty]').fill('12')
        pricing.locator('[name=retailPrice]').fill('3')
        pricing.locator('[name=wholesalePrice]').fill('2')
        pricing.locator('[name=distributorPrice]').fill('1.5')
        pricing.locator('[name=deliveryPerCase]').fill('6')
        pricing.get_by_role('button',name='Save price plan').click()
        page.get_by_text('Channel pricing plan saved. Source-app prices were not changed.').wait_for()
        page.get_by_role('heading',name='Channel comparison',exact=True).wait_for()
        page.screenshot(path=str(args.screenshots/'channel-pricing.png'),full_page=True)
        # Import actual supported vendor data shape through file preview and commit.
        page.locator('nav [data-view=imports]').click()
        form=page.locator('#import-form')
        form.locator('[name=source]').select_option('vendor')
        form.locator('[name=file]').set_input_files({'name':'vendor-test.json','mimeType':'application/json','buffer':json.dumps(vendor()).encode()})
        form.get_by_role('button',name='Preview import').click()
        page.get_by_role('button',name='Import into company ledger').wait_for()
        page.get_by_role('button',name='Import into company ledger').click()
        page.get_by_text('Imported 3 new records',exact=False).wait_for()
        # Stock planning stays distinct from ledger postings and source stock.
        page.locator('nav [data-view=inventory]').click()
        page.get_by_role('button',name='Plan',exact=True).first.click()
        plan=page.locator('#item-plan-form')
        plan.locator('[name=reorderPoint]').fill('20')
        plan.locator('[name=targetStock]').fill('100')
        plan.locator('[name=leadTimeDays]').fill('7')
        plan.get_by_role('button',name='Save inventory plan').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.get_by_text('100 units suggested',exact=True).wait_for()
        # Actual attachment stored with a source record.
        page.locator('nav [data-view=invoices]').click()
        page.get_by_role('button',name='View',exact=True).first.click()
        page.locator('#attachment-form [name=file]').set_input_files({'name':'invoice-note.txt','mimeType':'text/plain','buffer':b'Browser-test supporting document'})
        page.get_by_role('button',name='Add attachment',exact=True).click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.get_by_role('button',name='View',exact=True).first.click()
        page.get_by_role('link',name='invoice-note.txt').wait_for()
        page.locator('#detail').get_by_role('button',name='Close',exact=True).click()
        # Register equipment, depreciate it, and verify its printable schedule.
        page.locator('nav [data-view=assets]').click()
        page.get_by_role('button',name='+ Register equipment').click()
        asset=page.locator('#asset-form')
        asset.locator('[name=name]').fill('Bottling machine')
        asset.locator('[name=purchaseDate]').fill('2025-01-01')
        asset.locator('[name=startMonth]').fill('2025-01')
        asset.locator('[name=cost]').fill('1200')
        asset.locator('[name=salvage]').fill('120')
        asset.locator('[name=lifeMonths]').fill('12')
        asset.get_by_role('button',name='Register equipment',exact=True).click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.get_by_role('button',name='Post depreciation',exact=True).first.click()
        dep=page.locator('#depreciate-form')
        dep.locator('[name=throughMonth]').fill('2025-12')
        dep.get_by_role('button',name='Post monthly depreciation').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.screenshot(path=str(args.screenshots/'equipment.png'),full_page=True)
        # Payroll records are separate from live provider operation.
        page.locator('nav [data-view=payroll]').click()
        page.get_by_role('button',name='+ Local employee').click()
        employee=page.locator('#employee-form')
        employee.locator('[name=name]').fill('Pat Example')
        employee.locator('[name=jobTitle]').fill('Production')
        employee.get_by_role('button',name='Save employee').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.get_by_role('button',name='Record external payroll').click()
        payroll=page.locator('#local-payroll-form')
        payroll.locator('[name=date]').fill('2026-10-15')
        payroll.locator('[name=periodStart]').fill('2026-10-01')
        payroll.locator('[name=periodEnd]').fill('2026-10-15')
        payroll.locator('[name=gross]').fill('1000')
        payroll.locator('[name=federal]').fill('100')
        payroll.locator('[name=socialSecurity]').fill('62')
        payroll.locator('[name=medicare]').fill('14.50')
        payroll.locator('[name=employerSocialSecurity]').fill('62')
        payroll.locator('[name=employerMedicare]').fill('14.50')
        payroll.get_by_role('button',name='Post external payroll record').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.screenshot(path=str(args.screenshots/'payroll.png'),full_page=True)
        with page.expect_popup() as popup:
            page.get_by_role('link',name='Pay stub',exact=True).first.click()
        statement=popup.value
        statement.get_by_role('heading',name='Payroll earnings statement',exact=True).wait_for()
        statement.pdf(path=str(args.screenshots/'payroll-statement.pdf'),format='Letter',print_background=True)
        statement.close()
        # Post a balanced opening-balance entry and reconcile it.
        page.locator('nav [data-view=transactions]').click()
        page.get_by_role('button',name='+ Journal entry').click()
        form=page.locator('#journal-form')
        form.locator('[name=date]').fill('2026-11-01')
        form.locator('[name=memo]').fill('Opening bank balance')
        form.locator('.journal-row').nth(1).locator('select').select_option('1020')
        form.locator('.journal-row').nth(1).locator('[name=debit]').fill('1000')
        form.locator('.journal-row').nth(2).locator('select').select_option('3100')
        form.locator('.journal-row').nth(2).locator('[name=credit]').fill('1000')
        form.get_by_role('button',name='Post journal').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        page.locator('nav [data-view=reconcile]').click()
        form=page.locator('#reconcile-form')
        form.locator('[name=date]').fill('2026-11-30')
        form.locator('[name=ending]').fill('1000')
        bank_row=form.get_by_role('row').filter(has_text='Opening')
        # IDs are UUIDs; match journal amount rather than a display memo.
        form.get_by_role('row').filter(has_text='$1,000.00').locator('input[type=checkbox]').check()
        form.get_by_role('button',name='Finish reconciliation').click()
        page.get_by_text('Saved to your company books.',exact=True).wait_for()
        # Reports and overview render using the merged books.
        page.locator('nav [data-view=reports]').click()
        page.get_by_role('heading',name='Profit & loss',exact=True).wait_for()
        page.screenshot(path=str(args.screenshots/'financial-reports.png'),full_page=True)
        page.locator('nav [data-view=printing]').click()
        with page.expect_popup() as popup:
            page.get_by_role('link',name='Open print layout →').nth(1).click()
        printable=popup.value
        printable.get_by_role('heading',name='Profit & loss',exact=True).wait_for()
        printable.pdf(path=str(args.screenshots/'profit-loss.pdf'),format='Letter',print_background=True)
        printable.close()
        page.locator('nav [data-view=overview]').click()
        page.screenshot(path=str(args.screenshots/'overview.png'),full_page=True)
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(args.screenshots/'mobile-overview.png'),full_page=True)
        page.set_viewport_size({'width':1440,'height':1050})
        page.locator('nav [data-view=settings]').click()
        page.get_by_role('button',name='Sign out',exact=True).click()
        page.locator('#login-form').wait_for()
        assert not page.locator('#content').inner_text().strip()
        assert page.request.get(args.url+'/api/state').status==403
        assert not errors,errors
        browser.close()
    print('PASS: owner setup/login/logout, expense, production costing, pricing, inventory planning, vendor import, attachment, equipment/depreciation, payroll record, printable payroll/P&L PDFs, journal, reconciliation, reports, desktop/mobile rendering; no page errors.')


if __name__=='__main__':main()
